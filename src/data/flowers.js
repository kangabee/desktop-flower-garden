/** 꽃머리 중심(c)에서 반지름 r 위에 놓이는 픽셀들 (시계꽃의 실 무늬 같은 고리) */
const ring = (c, r, ch) => {
  const pts = [];
  for (let y = 0; y <= 2 * c; y++) {
    for (let x = 0; x <= 2 * c; x++) {
      if (Math.abs(Math.hypot(x - c, y - c) - r) < 0.5) pts.push([x, y, ch]);
    }
  }
  return pts;
};

const radial = (opts, extra = []) => {
  const rows = radialHead(opts).map((r) => [...r]);
  // extra: [x, y, 글자] — 생성된 꽃머리 위에 덧그릴 픽셀 (히비스커스 수술 등)
  for (const [x, y, ch] of extra) rows[y][x] = ch;
  const c = (opts.size - 1) / 2;
  return { rows: rows.map((r) => r.join('')), anchor: [c, c] };
};

